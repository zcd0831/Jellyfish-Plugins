package zcd.jellyfish.plugin.tools;

/**
 * 工具对文件路径的访问性质：决定它受哪一道路径闸门管。
 * <p>
 * <b>为什么由工具自己声明，而不是在闸门里列一张工具名清单</b>：清单会漂移——工具改名、新增一个
 * 文件工具、或某个工具换了参数名，闸门都不会知道，而漂移的方向正是<b>闸门被绕过</b>（报告里
 * {@code G-31}/{@code G-33} 都是「配置/清单与实现不同步」这一类）。声明放在工具类里，
 * 三者（工具实现、名片、访问性质）在同一处，改名时编译器会拦住。
 * <p>
 * <b>为什么不区分得更细</b>（例如再加一档「创建 / 覆盖 / 删除」）：闸门的判据是「这个路径在不在
 * 允许范围内」，与动作种类的细分无关；多出来的档位没有对应的策略可写，只会变成没人用的枚举值。
 *
 * @author zcd
 */
enum PathAccess {

    /** 不碰文件路径：不属路径闸门管（例如 {@code ask_user}）。 */
    NONE,

    /** 读路径：受「读」方向策略管。 */
    READ,

    /** 写路径：受「写」方向策略管。 */
    WRITE
}
