package zcd.jellyfish.plugin.pet;

/**
 * 宠物的姿态：它的样子是行为累积出来的结果。
 * <p>
 * <b>为什么姿态是固定精灵、不是模型生成的</b>：插件没有独立发起模型调用的通路——它能让模型看见东西的
 * 唯一方式是把内容投进正在跑的回合，而那会把宠物形态绑死在某一次回合上。因此本插件按
 * <b>固定精灵 + 行为演化</b>的形态成立。这不是退而求其次：<b>工作镜的力量在演化，不在初始外观</b>，
 * 一只由你今天的会话养出来的宠物，比一只你描述出来的宠物更像镜子。
 * <p>
 * <b>姿态按「最需要被看见」排序</b>：一个会话可能同时满足好几个条件（又疲惫又受了伤），
 * 而精灵只有一张脸。优先级是 {@code 伤痕 > 警惕 > 疲惫 > 寻常}——伤是既成事实、
 * 警惕是当下的应激、疲惫是缓慢累积，越靠前越该占据那张脸。
 * <p>
 * <b>它是「会变的宠物」，不是「会动的宠物」</b>：面板由外壳在特定时机来问一次（回合起止、会话切换、
 * 命令执行、插件主动报失效），不是每帧连续渲染。所以它不会在框里平滑游走，只会在有事发生时换一个姿态。
 * <p>
 * 不可变，可安全跨线程传递。
 *
 * @author zcd
 */
enum Posture {

    /** 寻常：没什么特别的。 */
    ORDINARY("寻常", new String[]{
            " \u2584\u2584\u2584\u2584\u2584\u2584\u2584\u2584 ",
            "\u2588 \u25cf    \u25cf \u2588",
            "\u2588   \u25bd\u25bd   \u2588",
            " \u2580\u2580\u2580\u2580\u2580\u2580\u2580\u2580 "}),

    /** 疲惫：连续工作太久，眼睛眯成一条线。 */
    TIRED("疲惫", new String[]{
            " \u2584\u2584\u2584\u2584\u2584\u2584\u2584\u2584 ",
            "\u2588 \u2500    \u2500 \u2588",
            "\u2588   \u2500\u2500   \u2588",
            " \u2580\u2580\u2580\u2580\u2580\u2580\u2580\u2580 "}),

    /** 警惕：被频繁打断，缩起身子、眼睛睁大。 */
    WARY("警惕", new String[]{
            "  \u2584\u2584\u2584\u2584\u2584\u2584  ",
            "  \u2588 \u2299 \u2299 \u2588 ",
            "  \u2588  \u25bd\u25bd  \u2588",
            "  \u2580\u2580\u2580\u2580\u2580\u2580  "}),

    /** 伤痕：工具连续失败留下来的一道疤。 */
    WOUNDED("伤痕", new String[]{
            " \u2584\u2584\u2584\u2584\u2584\u2584\u2584\u2584 ",
            "\u2588 \u25cf    \u25cf \u2588",
            "\u2588  \u2571 \u25bd\u25bd  \u2588",
            " \u2580\u2580\u2580\u2580\u2580\u2580\u2580\u2580 "});

    /** 形态名，进「形态」那一行。 */
    private final String label;

    /** 精灵的每一行，宽度固定为 10 列（半角字符，终端里就是 10 列）。 */
    private final String[] sprite;

    /**
     * 构造姿态。
     *
     * @param label  形态名
     * @param sprite 精灵行
     */
    Posture(String label, String[] sprite) {
        this.label = label;
        this.sprite = sprite;
    }

    /**
     * 取形态名。
     *
     * @return 形态名，保证非 {@code null}
     */
    String label() {
        return label;
    }

    /**
     * 取精灵行。
     * <p>
     * 返回内部数组的副本：调用方（面板）只读，而数组是可变类型，交出去就等于把不可变性交给了对方。
     *
     * @return 精灵行副本，保证非 {@code null}
     */
    String[] sprite() {
        return sprite.clone();
    }

    /**
     * 判断这是不是「寻常」。
     *
     * @return 寻常返回 {@code true}
     */
    boolean isOrdinary() {
        return this == ORDINARY;
    }
}
